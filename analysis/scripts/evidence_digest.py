"""Blog evidence digest: every number below is computed from trials.jsonl, none is typed by hand.

Usage:
    uv run python -m analysis.scripts.evidence_digest > docs/reports/blog-evidence.md

Reads the run in RUN_ID, restricts it to the pre-registered sample (experiments/sampling.py, 20 per
category, seed 7), and prints counts with their denominators. Counts, not percentages, wherever a
stratum is small (spec section 24). Every aggregate carries the diagnostic-distribution caveat.
"""

from __future__ import annotations

import json
from collections import Counter

from agent.schemas.loaders import REPO_ROOT, load_ground_truth
from experiments.sampling import select_cases

RUN_ID = "baseline_v1-20261002T092914Z"
CAVEAT = (
    "Diagnostic distribution: the dataset is synthetic with 20 cases per category, chosen to "
    "exercise each failure type. These are counts on that set, not prevalence in real documents."
)


def load() -> list[dict]:
    latest: dict[tuple[str, int], dict] = {}
    for line in (REPO_ROOT / "results/raw" / RUN_ID / "trials.jsonl").read_text().splitlines():
        row = json.loads(line)
        latest[(row["case_id"], row["trial_id"])] = row
    measured = [r for r in latest.values() if not r["harness_error"]]
    ids = {
        c.case_id
        for c in select_cases(
            load_ground_truth("v1"), 20, 7, prefer={r["case_id"] for r in measured}
        )
    }
    # Trial 1 only. Trials 2 and 3 exist for a 28-case consistency subset, and pooling them would
    # weight those cases three times (docs/decisions/decisions.md, 2026-10-17). Consistency is
    # reported in the run's processed report, not here.
    return [r for r in measured if r["case_id"] in ids and r["trial_id"] == 1]


def failed_tool_calls(case_ids: set[str]) -> tuple[int, int, Counter]:
    total = hits = 0
    shapes: Counter = Counter()
    for path in (REPO_ROOT / "results/traces" / RUN_ID).glob("*.json"):
        if path.name.removesuffix("-t1.json") not in case_ids:
            continue
        events = json.loads(path.read_text())["events"]
        failed = [e for e in events if e["ok"] is False]
        total += 1
        for e in failed:
            shapes[(e["tool"], json.dumps(e["arguments"]), e["error"])] += 1
        hits += bool(failed)
    return total, hits, shapes


def main() -> None:
    rows = load()
    n = len(rows)
    strict = [r for r in rows if r["scoring_mode"] == "strict"]
    cats = sorted({r["case_category"] for r in rows})
    out = [
        f"# Blog evidence digest — `{RUN_ID}`",
        "",
        f"Generated by `analysis/scripts/evidence_digest.py`. {n} trials, dataset `v1`, "
        "model `gemini-3.5-flash-lite`, prompt `p1`, tools `t1`, agent `v1`, 1 trial per case.",
        "",
        f"> {CAVEAT}",
        "",
        "## Outcome by category (posts 1, 2, 3)",
        "",
        "| category | n | status correct | full pass | safety violations |",
        "|---|---|---|---|---|",
    ]
    for c in cats:
        g = [r for r in rows if r["case_category"] == c]
        out.append(
            f"| {c} | {len(g)} | {sum(r['status_correct'] == 1 for r in g)}/{len(g)} | "
            f"{sum(r['deterministic_result'] == 'pass' for r in g)}/{len(g)} | "
            f"{sum(r['safety_violations'] for r in g)} |"
        )
    out += [
        "",
        f"Strict stratum: {len(strict)} cases; accept-set stratum (ambiguous): "
        f"{n - len(strict)} cases, reported separately (spec 8.3).",
        "",
        "## Safety violations by check (posts 3, 5)",
        "",
    ]
    s = Counter(i for r in rows for i in r["safety_violation_ids"])
    for k in sorted(s):
        cases = sorted({r["case_id"] for r in rows if k in r["safety_violation_ids"]})
        out.append(f"- {k}: {s[k]} violations across {len(cases)} trials. e.g. {', '.join(cases[:4])}")
    chk = [r for r in rows if r["evidence_checked"]]
    out += [
        "",
        "## Evidence quality (posts 3, 5)",
        "",
        f"- trials with evidence checked: {len(chk)}",
        f"- section cited correctly: {sum(r['evidence_section_correct'] for r in chk)} of "
        f"{sum(r['evidence_checked'] for r in chk)} evidence items",
        f"- quote verbatim in document: {sum(r['evidence_quote_verbatim'] for r in chk)} of "
        f"{sum(r['evidence_checked'] for r in chk)}",
        f"- offsets consistent with the quote: {sum(r['evidence_offsets_consistent'] for r in chk)} of "
        f"{sum(r['evidence_checked'] for r in chk)}",
        f"- fabricated quotes (S2): {sum(r['fabricated_evidence_count'] for r in rows)}",
        "",
        "Reading: the agent finds the right section and quotes it, then reports character offsets "
        "that do not match the quote, although the tool returned the correct ones.",
        "",
        "## Tool use and trajectory (posts 4, 5)",
        "",
    ]
    total, hits, shapes = failed_tool_calls({r["case_id"] for r in rows})
    out += [
        f"- tool calls per trial, mean: {sum(r['num_tool_calls'] for r in rows) / n:.1f}",
        f"- redundant calls: {sum(r['num_redundant_calls'] for r in rows)} total; loops detected: "
        f"{sum(bool(r['loop_detected']) for r in rows)} trials",
        f"- output repaired once: {sum(r['output_validation'] == 'repaired' for r in rows)} trials; "
        f"never unparseable: {sum(r['output_validation'] == 'unparseable' for r in rows)}",
        f"- traces with a failed tool call: {hits} of {total}. Failed calls by shape: "
        + "; ".join(f"{t} {a} -> {e} x{c}" for (t, a, e), c in shapes.most_common(3)),
        "",
        "Reading: every trace makes the same wasted first policy lookup, passing the policy id as a "
        "rule id. It is a systematic prompt/tool-contract issue, not noise (prompt p1 unchanged).",
        "",
        "## Cost and runtime (posts 1, 7)",
        "",
        f"- model requests per trial, mean: {sum(r['num_llm_calls'] for r in rows) / n:.1f}",
        f"- tokens per trial, mean: {sum(r['total_tokens'] for r in rows) / n:.0f}",
        f"- tokens total: {sum(r['total_tokens'] for r in rows)}",
        "",
        "## Where to look for examples",
        "",
        "Traces live in `results/traces/" + RUN_ID + "/<case_id>-t1.json`; the row for the same "
        "trial is in `results/raw/" + RUN_ID + "/trials.jsonl`.",
        "",
    ]
    for label, pick in (
        ("S3 invented offsets (post 5)", lambda r: "S3" in r["safety_violation_ids"]),
        ("S2 fabricated quote and S1 (post 5)", lambda r: "S2" in r["safety_violation_ids"]),
        (
            "contradiction missed, answered COMPLIANT (posts 1, 3)",
            lambda r: r["case_category"] == "contradictory" and r["status_correct"] != 1,
        ),
        (
            "correct on a contradiction (the single case)",
            lambda r: r["case_category"] == "contradictory" and r["status_correct"] == 1,
        ),
    ):
        ids = sorted(r["case_id"] for r in rows if pick(r))
        out.append(f"- {label}: {len(ids)} trials, e.g. {', '.join(ids[:5])}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
